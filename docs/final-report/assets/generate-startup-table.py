#!/usr/bin/env python3
"""TODO(team): Rebuild the E1 startup table from archived sessions; no experiments run."""
import csv
from pathlib import Path
from statistics import mean

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / "results/compact-study/sessions.csv"
SUMMARY = ROOT / "results/compact-study/summary.csv"
OUTPUT = Path(__file__).with_name("startup-table.tex")


def main():
    sessions = list(csv.DictReader(SOURCE.open(newline="")))
    summary = {r["run_id"]: r for r in csv.DictReader(SUMMARY.open(newline=""))}
    lines = [
        "% TODO(team): Present E1 startup delays computed from archived sessions.",
        "% Generated by assets/generate-startup-table.py from archived sessions.csv.",
        r"\begin{table}[ht]",
        r"\centering\small",
        r"\caption{E1 startup delay over completed sessions, pooled across the",
        r"three paired contexts. Times are seconds from session start; the",
        r"range is the minimum and maximum among completed sessions.}",
        r"\label{tab:e1-startup}",
        r"\begin{tabular}{@{}llrrr@{}}",
        r"\toprule",
        r"Demand & Policy & Completed & Mean & Range \\",
        r"\midrule",
    ]
    for load, scheduled in [("low", 6), ("high", 18)]:
        for policy in ["N", "OFF", "S"]:
            group = [r for r in sessions if r["load"] == load
                     and r["policy"] == policy and r["grace"] == "3"
                     and r["outage"] == "persistent" and r["second_delay_s"] == "0"]
            assert len(group) == scheduled
            assert len({(r["run_id"], r["viewer"]) for r in group}) == scheduled
            done = [r for r in group if r["status"] == "completed"]
            for run_id in {r["run_id"] for r in group}:
                per_run = [float(r["startup_delay_ms"]) / 1000 for r in done
                           if r["run_id"] == run_id]
                archived = summary[run_id]
                assert len(per_run) == int(archived["completed"])
                if per_run:
                    assert abs(mean(per_run) - float(archived["mean_startup_s_completed"])) < 1e-8
            times = [float(r["startup_delay_ms"]) / 1000 for r in done]
            lines.append(f"{load.title()} & {policy} & {len(done)}/{scheduled} & "
                         f"{mean(times):.2f} & {min(times):.2f}--{max(times):.2f} " + r"\\")
    lines.extend([r"\bottomrule", r"\end{tabular}", r"\end{table}"])
    OUTPUT.write_text("\n".join(lines) + "\n")
    print("Rebuilt E1 startup table; session counts and run means match archived summary.")


if __name__ == "__main__":
    main()
